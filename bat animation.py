pixel = 6
delay = 67
width = 590
height = 335

pygame.init()
screen = pygame.display.set_mode((width, height))
pygame.display.set_caption("pixelated bat animation")
clock = pygame.time.Clock()

small_w = width // 4
small_h = height // 4
small = pygame.Surface((small_w, small_h))
for y in range(small_h):
    for x in range(small_w):
        px = x * 4
        py = y * 4
        dx = px - 440
        dy = py + 10
        spread = 110 if dx < 0 else 200
        dist = ((dx / spread) ** 2 + (dy / 230) ** 2) ** 0.5
        shade = 32 * max(0, 1 - dist * dist * 0.6) ** 1.5
        value = int(254 - shade)
        small.set_at((x, y), (value, value, value))
background = pygame.transform.smoothscale(small, (width, height))

surfaces = []
for frame in frames:
    surface = pygame.Surface((len(frame[0]) * pixel, len(frame) * pixel), pygame.SRCALPHA)
    for y, row in enumerate(frame):
        for x, char in enumerate(row):
            if char == "#":
                pygame.draw.rect(surface, (27, 27, 27), (x * pixel, y * pixel, pixel, pixel))
    surfaces.append(surface)

index = 0
last_change = pygame.time.get_ticks()
running = True

while running:
    for event in pygame.event.get():
        if event.type == pygame.QUIT:
            running = False

    now = pygame.time.get_ticks()
    if now - last_change >= delay:
        index = (index + 1) % len(surfaces)
        last_change = now

    screen.blit(background, (0, 0))
    current = surfaces[index]
    rect = current.get_rect(center=(width // 2, height // 2))
    screen.blit(current, rect)
    pygame.display.flip()
    clock.tick(60)

pygame.quit()